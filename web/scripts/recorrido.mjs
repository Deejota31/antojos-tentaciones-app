// Recorrido de humo en modo demo con un navegador real: venta con pago parcial, doble clic, cobro del saldo,
// cancelación con devolución pendiente, gasto de caja y cierre. Uso: CHROMIUM_PATH=... node scripts/recorrido.mjs
import { chromium } from '@playwright/test'

const BASE = process.env.BASE_URL || 'http://localhost:4173/'
const W = Number(process.env.ANCHO || 390)
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] })
const page = await (await browser.newContext({ viewport: { width: W, height: 844 }, isMobile: W < 800, hasTouch: W < 800, timezoneId: 'America/Lima' })).newPage()
const errores = []
page.on('pageerror', e => errores.push(e.message))
const paso = m => console.log('✓', m)
const toast = async re => { await page.getByRole('status').filter({ hasText: re }).first().waitFor({ timeout: 8000 }) }

await page.goto(BASE + '?demo')
await page.getByLabel('Clave').fill('mala')
await page.getByRole('button', { name: 'Entrar' }).click()
await page.getByText('Clave incorrecta').waitFor(); paso('clave incorrecta rechazada')
await page.getByLabel('Clave').fill('demo')
await page.getByRole('button', { name: 'Entrar' }).click()
await page.getByRole('heading', { name: 'Inicio' }).waitFor(); paso('sesión iniciada')

await page.evaluate(() => { location.hash = 'vender' })
await page.getByRole('button', { name: /^Hamburguesa Doble/ }).first().click()
await page.getByRole('button', { name: /^Hamburguesa Doble/ }).first().click()
const bebida = page.getByRole('button', { name: /Salchibroaster/ })
if (!(await bebida.isDisabled())) throw new Error('Salchibroaster sin precio debería estar bloqueada')
paso('producto sin precio bloqueado')
if (W < 768) await page.getByRole('button', { name: /Ver pedido/ }).click()
const ticket = W < 768 ? page.getByRole('dialog', { name: 'Pedido', exact: true }) : page.locator('aside').last()
await ticket.getByRole('radio', { name: 'Parcial' }).click()
await ticket.getByLabel('Monto recibido (S/)').fill('10')
await ticket.getByRole('radio', { name: 'Yape' }).click()
await ticket.getByRole('button', { name: 'Revisar y guardar' }).click()
await page.getByText('Saldo por cobrar').waitFor()
const guardar = page.getByRole('button', { name: 'Guardar venta' })
await guardar.dblclick()
await toast(/Venta .* guardada: S\/ 26.00/); paso('venta guardada con pago parcial (doble clic)')

await page.evaluate(() => { location.hash = 'pedidos' })
await page.getByRole('button', { name: /^Por cobrar \(/ }).click()
await page.waitForTimeout(600)
const nVentas = await page.getByText('Saldo S/ 16.00').count()
if (nVentas !== 1) throw new Error(`Se esperaba 1 pedido con saldo 16, hay ${nVentas}`)
paso('una sola venta con saldo S/ 16.00 (sin duplicados)')
if (W >= 1280) await page.getByRole('row').filter({ hasText: 'S/ 16.00' }).getByRole('button').first().click()
else await page.getByText('Saldo S/ 16.00').click()
await page.getByRole('button', { name: 'Registrar cobro' }).first().click()
await page.getByRole('dialog').getByRole('button', { name: 'Registrar cobro' }).last().click()
await toast(/Cobro registrado: S\/ 16.00/); paso('saldo cobrado')
await page.getByRole('button', { name: 'Cancelar pedido' }).first().click()
await page.getByPlaceholder('Ej. el cliente desistió').fill('Prueba')
await page.getByRole('radio', { name: 'Queda pendiente de devolver' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Cancelar pedido' }).last().click()
await page.getByRole('dialog', { name: 'Cancelar pedido' }).getByRole('button', { name: 'Cancelar pedido' }).click()
await toast(/cancelado/); paso('pedido pagado cancelado con devolución pendiente')
await page.getByRole('dialog').getByText('Devolución pendiente').first().waitFor(); paso('estado de pago: devolución pendiente')
await page.keyboard.press('Escape')

await page.evaluate(() => { location.hash = 'caja' })
await page.getByText('Efectivo esperado en caja').waitFor()
await page.getByRole('button', { name: 'Cerrar caja' }).click()
await page.getByLabel('Efectivo contado (S/)').fill('1')
await page.getByText(/Falta S\/ /).waitFor()
await page.getByRole('dialog').getByLabel(/Observación/).fill('Prueba de cierre')
await page.getByRole('dialog').getByRole('button', { name: 'Cerrar caja' }).click()
await page.getByRole('dialog', { name: 'Confirmar cierre' }).getByRole('button', { name: 'Cerrar caja' }).click()
await toast(/Caja cerrada/); paso('caja cerrada con diferencia y observación')
await page.getByRole('heading', { name: 'Abrir caja' }).waitFor()

if (errores.length) throw new Error('Errores de página: ' + errores.join(' | '))
console.log('Recorrido completo sin errores de página.')
await browser.close()
